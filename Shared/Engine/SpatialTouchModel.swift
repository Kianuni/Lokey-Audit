import CoreGraphics
import Foundation
import simd

/// A single key tap sample captured from the touch surface.
public struct TouchSample: Sendable, Equatable {
    /// Primary key character directly hit (lowercase `'a'...'z'` or `'\''`).
    public let primaryChar: Character
    /// Normalized coordinate within the keyboard letter grid (`x` in `0...1`, `y` in `0...1`),
    /// or `nil` when synthesized without spatial deviation (e.g., exact center tap).
    public let normalizedPoint: CGPoint?

    public init(primaryChar: Character, normalizedPoint: CGPoint? = nil) {
        self.primaryChar = primaryChar
        self.normalizedPoint = normalizedPoint
    }
}

/// Weighted letter hypothesis generated by the 2D Gaussian spatial touch model.
public struct KeyHypothesis: Sendable, Equatable {
    public let char: Character
    /// Non-negative penalty in Q8 log10 units (`0` = dead-center / primary match, larger = further away).
    public let penaltyQ8: Int

    public init(char: Character, penaltyQ8: Int) {
        self.char = char
        self.penaltyQ8 = penaltyQ8
    }
}

/// Pure-offline personal 26-key spatial calibration profile persisted inside the shared `App Group` container (`< 2.5 KB`).
/// Stores online EMA centroid offsets `(meanOffsetX, meanOffsetY)` and 2×2 thumb-tilt second moments `(varX, varY, covXY)`.
public struct LokeyTouchCalibration: Codable, Equatable, Sendable {
    public struct KeyStats: Codable, Equatable, Sendable {
        public var sampleCount: Int
        public var meanOffsetX: Double
        public var meanOffsetY: Double
        public var varX: Double
        public var varY: Double
        public var covXY: Double

        public init(
            sampleCount: Int = 0,
            meanOffsetX: Double = 0,
            meanOffsetY: Double = 0,
            varX: Double = 0,
            varY: Double = 0,
            covXY: Double = 0
        ) {
            self.sampleCount = sampleCount
            self.meanOffsetX = meanOffsetX
            self.meanOffsetY = meanOffsetY
            self.varX = varX
            self.varY = varY
            self.covXY = covXY
        }
    }

    /// Hard guardrail: personal key centroid may never drift beyond `±20%` of 1 horizontal key pitch
    /// or `±14%` of 1 vertical row pitch, guaranteeing physical keycaps can never invert or warp.
    public static let maxHorizontalShiftRatio: Double = 0.20
    public static let maxVerticalShiftRatio: Double = 0.14
    private static let storageKey = "com.kianuni.lokey.touch_calibration.v1"

    public var perKey: [String: KeyStats]
    public var totalCommittedTaps: Int

    public init(perKey: [String: KeyStats] = [:], totalCommittedTaps: Int = 0) {
        self.perKey = perKey
        self.totalCommittedTaps = totalCommittedTaps
    }

    /// Number of alphabetic keys (`a–z`) that have accumulated at least 4 confirmed touch samples.
    public var calibratedKeyCount: Int {
        perKey.values.reduce(0) { $0 + ($1.sampleCount >= 4 ? 1 : 0) }
    }

    public static func load(from defaults: UserDefaults? = nil) -> LokeyTouchCalibration {
        if defaults == nil,
           let fileURL = LokeyAppGroup.sharedTouchCalibrationFileURL(),
           let fileData = try? Data(contentsOf: fileURL),
           let decoded = try? JSONDecoder().decode(LokeyTouchCalibration.self, from: fileData) {
            return decoded
        }
        let store = defaults ?? LokeyAppGroup.sharedDefaults()
        guard let data = store.data(forKey: storageKey),
              let decoded = try? JSONDecoder().decode(LokeyTouchCalibration.self, from: data) else {
            return LokeyTouchCalibration()
        }
        return decoded
    }

    public func save(to defaults: UserDefaults? = nil) {
        guard let data = try? JSONEncoder().encode(self) else { return }
        if defaults == nil, let fileURL = LokeyAppGroup.sharedTouchCalibrationFileURL() {
            if (try? data.write(to: fileURL, options: .atomic)) != nil {
                return
            }
        }
        let store = defaults ?? LokeyAppGroup.sharedDefaults()
        store.set(data, forKey: Self.storageKey)
    }

    public static func reset(in defaults: UserDefaults? = nil, broadcast: Bool = true) {
        if defaults == nil, let fileURL = LokeyAppGroup.sharedTouchCalibrationFileURL() {
            try? FileManager.default.removeItem(at: fileURL)
        }
        let store = defaults ?? LokeyAppGroup.sharedDefaults()
        store.removeObject(forKey: storageKey)
        if broadcast && defaults == nil {
            LokeyIPC.postSettingsChanged()
        }
    }
}

/// Models the physical 26-key iOS QWERTY layout to recover adjacent-key blind-typing typos,
/// augmented with Apple Silicon SIMD 2×2 full-covariance tilted Gaussian scoring and bounded online EMA calibration.
public final class SpatialTouchModel: @unchecked Sendable {
    public struct KeyAnchor: Sendable {
        public let char: Character
        public let center: CGPoint
    }

    private struct EffectiveKeyProfile {
        let effectiveCenter: SIMD2<Double>
        /// Precomputed symmetric `0.5 * Σ_k^{-1}` so `normDistSq = simd_dot(d, precisionHalf * d)` runs in 1 SIMD op.
        let precisionHalf: simd_double2x2
    }

    /// Standard iOS portrait 3-row alphabetic centers normalized to `[0, 1] x [0, 1]`.
    /// Row 0 (Q-P): 10 keys, pitch = 0.10, centers at 0.05 ... 0.95, y = 0.167
    /// Row 1 (A-L): 9 keys, 5% side indent, pitch = 0.10, centers at 0.10 ... 0.90, y = 0.500
    /// Row 2 (Z-M): 7 keys centered, pitch = 0.10, centers at 0.20 ... 0.80, y = 0.833
    public private(set) var anchors: [KeyAnchor]
    private var anchorByChar: [Character: CGPoint] = [:]
    private var effectiveProfiles: [Character: EffectiveKeyProfile] = [:]
    private var anchorByIndex = [KeyAnchor?](repeating: nil, count: 26)
    private var centerByIndex = [CGPoint?](repeating: nil, count: 26)
    private var profileByIndex = [EffectiveKeyProfile?](repeating: nil, count: 26)
    private var adjacentMasks = [UInt32](repeating: 0, count: 26)
    private var horizAdjacentMasks = [UInt32](repeating: 0, count: 26)
    private var wideMasks165 = [UInt32](repeating: 0, count: 26)
    private var twoHopMasks = [UInt32](repeating: 0, count: 26)
    private var allAnchorMask: UInt32 = 0
    private var hasNonASCIILetterAnchor: Bool = false
    private var staticCenterHypotheses = [[KeyHypothesis]?](repeating: nil, count: 26)
    private static let lowerCharByIndex: [Character] = Array("abcdefghijklmnopqrstuvwxyz")

    @inline(__always)
    private static func asciiKeyIndex(_ ch: Character) -> Int {
        guard let v = ch.asciiValue else { return -1 }
        if v >= 0x61 && v <= 0x7A { return Int(v - 0x61) }
        if v >= 0x41 && v <= 0x5A { return Int(v - 0x41) }
        return -1
    }

    @inline(__always)
    private static func asciiByteIndex(_ b: UInt8) -> Int {
        if b >= 0x61 && b <= 0x7A { return Int(b - 0x61) }
        if b >= 0x41 && b <= 0x5A { return Int(b - 0x41) }
        return -1
    }

    private var minAnchorX: CGFloat = 0.05
    private var maxAnchorX: CGFloat = 0.95
    private var minAnchorY: CGFloat = 1.0 / 6.0
    private var maxAnchorY: CGFloat = 5.0 / 6.0
    private var keyPitchX: CGFloat = 0.10
    private var rowPitchY: CGFloat = 1.0 / 3.0

    /// Scale-invariant Gaussian sigmas derived from actual normalized key pitch (`keyPitchX`, `rowPitchY`).
    private var sigmaX: CGFloat = 0.0725
    private var sigmaY: CGFloat = 0.215

    /// Personal adaptive calibration state (active in portrait layout; bypassed in landscape so thumb geometry never mixes).
    public private(set) var calibration: LokeyTouchCalibration
    public private(set) var modelGeneration: UInt64 = 0
    public var isLandscapeLayout: Bool = false {
        didSet {
            if oldValue != isLandscapeLayout {
                modelGeneration &+= 1
            }
        }
    }
    private var dirtyLearnedTapCount: Int = 0

    public init(
        customAnchors: [KeyAnchor]? = nil,
        calibration: LokeyTouchCalibration = LokeyTouchCalibration()
    ) {
        if let customAnchors, !customAnchors.isEmpty {
            self.anchors = customAnchors
        } else {
            self.anchors = Self.defaultNativeAnchors()
        }
        self.calibration = calibration
        rebuildLookupAndBounds()
    }

    public func updateAnchors(_ newAnchors: [KeyAnchor]) {
        guard !newAnchors.isEmpty else { return }
        self.anchors = newAnchors
        rebuildLookupAndBounds()
    }

    public func setCalibration(_ newCalibration: LokeyTouchCalibration) {
        self.calibration = newCalibration
        self.dirtyLearnedTapCount = 0
        rebuildEffectiveProfiles()
    }

    public func reloadCalibrationFromDisk(defaults: UserDefaults? = nil) {
        self.calibration = LokeyTouchCalibration.load(from: defaults)
        self.dirtyLearnedTapCount = 0
        rebuildEffectiveProfiles()
    }

    public func resetCalibration(defaults: UserDefaults? = nil, broadcast: Bool = true) {
        LokeyTouchCalibration.reset(in: defaults, broadcast: broadcast)
        self.calibration = LokeyTouchCalibration()
        self.dirtyLearnedTapCount = 0
        rebuildEffectiveProfiles()
    }

    private static let calibrationSaveQueue = DispatchQueue(label: "com.kianuni.lokey.calibrationIO", qos: .utility)

    public func flushCalibrationToDiskIfNeeded(
        force: Bool = false,
        batchThreshold: Int = 12,
        defaults: UserDefaults? = nil
    ) {
        guard dirtyLearnedTapCount > 0 else { return }
        guard force || dirtyLearnedTapCount >= batchThreshold else { return }
        let snapshot = calibration
        dirtyLearnedTapCount = 0
        if defaults == nil {
            Self.calibrationSaveQueue.async {
                snapshot.save(to: nil)
            }
        } else {
            snapshot.save(to: defaults)
        }
    }

    private func rebuildLookupAndBounds() {
        anchorByChar.removeAll(keepingCapacity: true)
        for i in 0..<26 {
            anchorByIndex[i] = nil
            centerByIndex[i] = nil
            adjacentMasks[i] = 0
            horizAdjacentMasks[i] = 0
            wideMasks165[i] = 0
            twoHopMasks[i] = 0
            staticCenterHypotheses[i] = nil
        }
        allAnchorMask = 0
        hasNonASCIILetterAnchor = false

        var minX: CGFloat = 1.0
        var maxX: CGFloat = 0.0
        var minY: CGFloat = 1.0
        var maxY: CGFloat = 0.0
        for a in anchors {
            anchorByChar[a.char] = a.center
            let idx = Self.asciiKeyIndex(a.char)
            if idx >= 0 && a.char.asciiValue.map({ $0 >= 0x61 && $0 <= 0x7A }) == true {
                anchorByIndex[idx] = a
                centerByIndex[idx] = a.center
                allAnchorMask |= (UInt32(1) &<< idx)
            } else {
                hasNonASCIILetterAnchor = true
            }
            if a.center.x < minX { minX = a.center.x }
            if a.center.x > maxX { maxX = a.center.x }
            if a.center.y < minY { minY = a.center.y }
            if a.center.y > maxY { maxY = a.center.y }
        }
        for i in 0..<26 {
            guard let ca = centerByIndex[i] else { continue }
            var adj: UInt32 = 0
            var hadj: UInt32 = 0
            var wide: UInt32 = 0
            var twoHop: UInt32 = 0
            for j in 0..<26 {
                guard let cb = centerByIndex[j] else { continue }
                let dx = abs(ca.x - cb.x)
                let dy = abs(ca.y - cb.y)
                let bit = UInt32(1) &<< j
                if dx <= 0.145 && dy <= 0.42 { adj |= bit }
                if dx <= 0.145 && dy <= 0.06 { hadj |= bit }
                if dx <= 0.166 && dy <= 0.431 { wide |= bit }
                if dx <= 0.261 && dy <= 0.461 { twoHop |= bit }
            }
            adjacentMasks[i] = adj
            horizAdjacentMasks[i] = hadj
            wideMasks165[i] = wide
            twoHopMasks[i] = twoHop
        }
        if minX <= maxX {
            minAnchorX = minX
            maxAnchorX = maxX
            let pitchX = (maxX - minX) / 9.0
            if pitchX > 0.04 {
                keyPitchX = pitchX
                sigmaX = max(0.055, pitchX * 0.725)
            }
        }
        if minY <= maxY {
            minAnchorY = minY
            maxAnchorY = maxY
            let pitchY = (maxY - minY) / 2.0
            if pitchY > 0.10 {
                rowPitchY = pitchY
                sigmaY = max(0.180, pitchY * 0.640)
            }
        }
        rebuildEffectiveProfiles()
        if !hasNonASCIILetterAnchor {
            for i in 0..<26 where centerByIndex[i] != nil {
                staticCenterHypotheses[i] = computeASCIIHypotheses(
                    idx: i,
                    sample: TouchSample(primaryChar: Self.lowerCharByIndex[i], normalizedPoint: nil),
                    useAdaptiveCalibration: false,
                    maxCandidates: 7
                )
            }
        }
    }

    private func rebuildEffectiveProfiles() {
        modelGeneration &+= 1
        effectiveProfiles.removeAll(keepingCapacity: true)
        for i in 0..<26 { profileByIndex[i] = nil }
        for anchor in anchors {
            let prof = makeEffectiveProfile(for: anchor.char, physicalCenter: anchor.center)
            effectiveProfiles[anchor.char] = prof
            let idx = Self.asciiKeyIndex(anchor.char)
            if idx >= 0 && anchor.char.asciiValue.map({ $0 >= 0x61 && $0 <= 0x7A }) == true {
                profileByIndex[idx] = prof
            }
        }
    }

    private func makeEffectiveProfile(for char: Character, physicalCenter: CGPoint) -> EffectiveKeyProfile {
        let baseVarX = Double(sigmaX * sigmaX)
        let baseVarY = Double(sigmaY * sigmaY)

        guard let stats = calibration.perKey[String(char)], stats.sampleCount > 0 else {
            let inv2Vx = 0.5 / baseVarX
            let inv2Vy = 0.5 / baseVarY
            return EffectiveKeyProfile(
                effectiveCenter: SIMD2<Double>(Double(physicalCenter.x), Double(physicalCenter.y)),
                precisionHalf: simd_double2x2(
                    SIMD2<Double>(inv2Vx, 0.0),
                    SIMD2<Double>(0.0, inv2Vy)
                )
            )
        }

        // Smooth Bayesian confidence ramp (`0 -> 1` over 16 confirmed taps) + hard `±20%`X / `±14%`Y clamp
        let weight = min(1.0, Double(stats.sampleCount) / 16.0)
        let maxShiftX = Double(keyPitchX) * LokeyTouchCalibration.maxHorizontalShiftRatio
        let maxShiftY = Double(rowPitchY) * LokeyTouchCalibration.maxVerticalShiftRatio

        let clampedShiftX = min(maxShiftX, max(-maxShiftX, stats.meanOffsetX)) * weight
        let clampedShiftY = min(maxShiftY, max(-maxShiftY, stats.meanOffsetY)) * weight
        let effCenter = SIMD2<Double>(
            Double(physicalCenter.x) + clampedShiftX,
            Double(physicalCenter.y) + clampedShiftY
        )

        // Blend empirical 2×2 thumb-tilt covariance after >= 5 samples, strictly positive-definite (`|ρ| <= 0.42`)
        let covBlend = 0.35 * min(1.0, Double(max(0, stats.sampleCount - 4)) / 20.0)
        let empVarX = min(baseVarX * 1.30, max(baseVarX * 0.78, stats.varX > 0 ? stats.varX : baseVarX))
        let empVarY = min(baseVarY * 1.30, max(baseVarY * 0.78, stats.varY > 0 ? stats.varY : baseVarY))
        let vx = (1.0 - covBlend) * baseVarX + covBlend * empVarX
        let vy = (1.0 - covBlend) * baseVarY + covBlend * empVarY

        let maxAbsCov = 0.42 * sqrt(vx * vy)
        let cov = covBlend * min(maxAbsCov, max(-maxAbsCov, stats.covXY))
        let det = max(1e-12, vx * vy - cov * cov)
        let invTwoDet = 0.5 / det

        return EffectiveKeyProfile(
            effectiveCenter: effCenter,
            precisionHalf: simd_double2x2(
                SIMD2<Double>(vy * invTwoDet, -cov * invTwoDet),
                SIMD2<Double>(-cov * invTwoDet, vx * invTwoDet)
            )
        )
    }

    public func center(for char: Character) -> CGPoint? {
        let idx = Self.asciiKeyIndex(char)
        if idx >= 0 && !hasNonASCIILetterAnchor {
            return centerByIndex[idx]
        }
        return anchorByChar[Character(char.lowercased())]
    }

    /// Returns the calibrated personal centroid `(μx, μy)` for `char` in portrait mode.
    public func effectiveCenter(for char: Character) -> CGPoint? {
        let idx = Self.asciiKeyIndex(char)
        if idx >= 0 && !hasNonASCIILetterAnchor {
            if let prof = profileByIndex[idx] {
                return CGPoint(x: prof.effectiveCenter.x, y: prof.effectiveCenter.y)
            }
            return centerByIndex[idx]
        }
        let lower = Character(char.lowercased())
        guard let prof = effectiveProfiles[lower] else {
            return anchorByChar[lower]
        }
        return CGPoint(x: prof.effectiveCenter.x, y: prof.effectiveCenter.y)
    }

    /// Returns the learned thumb-tilt correlation `ρ` in `[-0.42, +0.42]` for `char` (for diagnostics & unit tests).
    public func learnedCorrelation(for char: Character) -> Double {
        let key = String(char.lowercased())
        guard let stats = calibration.perKey[key],
              stats.sampleCount >= 5,
              stats.varX > 1e-9,
              stats.varY > 1e-9 else {
            return 0.0
        }
        let raw = stats.covXY / sqrt(stats.varX * stats.varY)
        return min(0.42, max(-0.42, raw))
    }

    /// Online EMA calibration from a user-confirmed Pinyin commit.
    /// Enforces strict length-parity, transposition-exclusion, 1-neighbor locality, and Huber winsorization
    /// so acronyms, dropped vowels, fat-finger extra keys, or wild slips can NEVER pollute key centroids.
    @discardableResult
    public func recordConfirmedAlignment(
        samples: [TouchSample],
        intendedSyllables: [String]
    ) -> Int {
        guard !isLandscapeLayout, !samples.isEmpty, !intendedSyllables.isEmpty else {
            return 0
        }
        guard samples.allSatisfy({ $0.primaryChar != "'" && $0.normalizedPoint != nil }) else {
            return 0
        }

        let intendedChars = Array(intendedSyllables.joined().lowercased())
        guard intendedChars.count == samples.count else {
            return 0
        }

        let tappedChars: [Character] = samples.map { Character($0.primaryChar.lowercased()) }
        let pitchX = Double(keyPitchX)
        let pitchY = Double(rowPitchY)
        let maxGateX = pitchX * 1.15
        let maxGateY = pitchY * 0.85
        let huberCapX = pitchX * 0.55
        let huberCapY = pitchY * 0.42
        let maxShiftX = pitchX * LokeyTouchCalibration.maxHorizontalShiftRatio
        let maxShiftY = pitchY * LokeyTouchCalibration.maxVerticalShiftRatio
        let baseVarX = Double(sigmaX * sigmaX)
        let baseVarY = Double(sigmaY * sigmaY)
        let alpha = 0.08

        var skipNext = false
        var updatedCount = 0

        for i in 0..<intendedChars.count {
            if skipNext {
                skipNext = false
                continue
            }
            let intended = intendedChars[i]
            let tapped = tappedChars[i]
            guard intended >= "a" && intended <= "z" else { continue }

            // Skip adjacent 2-finger timing transpositions (e.g., `nhiao` -> `nihao`)
            if i + 1 < intendedChars.count,
               intended != tapped,
               intended == tappedChars[i + 1],
               intendedChars[i + 1] == tapped {
                skipNext = true
                continue
            }

            // Require exact hit or immediate 1-key physical neighbor
            guard intended == tapped || areKeysAdjacent(intended, tapped),
                  let physCenter = anchorByChar[intended],
                  let rawPt = samples[i].normalizedPoint else {
                continue
            }

            let clampedX = min(1.0, max(0.0, Double(rawPt.x)))
            let clampedY = min(1.0, max(0.0, Double(rawPt.y)))
            let rawDX = clampedX - Double(physCenter.x)
            let rawDY = clampedY - Double(physCenter.y)

            // Reject 2-key jumps or stray outliers
            guard abs(rawDX) <= maxGateX && abs(rawDY) <= maxGateY else {
                continue
            }

            // Huber-winsorize single-tap innovation so one-off edge taps cannot spike the mean
            let dx = min(huberCapX, max(-huberCapX, rawDX))
            let dy = min(huberCapY, max(-huberCapY, rawDY))

            let key = String(intended)
            var stats = calibration.perKey[key] ?? LokeyTouchCalibration.KeyStats(
                sampleCount: 0,
                meanOffsetX: 0.0,
                meanOffsetY: 0.0,
                varX: baseVarX,
                varY: baseVarY,
                covXY: 0.0
            )

            if stats.sampleCount == 0 {
                stats.varX = baseVarX
                stats.varY = baseVarY
            }

            let stepAlpha = stats.sampleCount < 6 ? 0.14 : alpha
            let prevMeanX = stats.meanOffsetX
            let prevMeanY = stats.meanOffsetY
            let newMeanX = min(maxShiftX, max(-maxShiftX, (1.0 - stepAlpha) * prevMeanX + stepAlpha * dx))
            let newMeanY = min(maxShiftY, max(-maxShiftY, (1.0 - stepAlpha) * prevMeanY + stepAlpha * dy))

            let resX = rawDX - newMeanX
            let resY = rawDY - newMeanY
            let covAlpha = 0.06
            stats.varX = min(baseVarX * 1.50, max(baseVarX * 0.65, (1.0 - covAlpha) * stats.varX + covAlpha * (resX * resX)))
            stats.varY = min(baseVarY * 1.50, max(baseVarY * 0.65, (1.0 - covAlpha) * stats.varY + covAlpha * (resY * resY)))
            let maxStoredCov = 0.50 * sqrt(stats.varX * stats.varY)
            stats.covXY = min(maxStoredCov, max(-maxStoredCov, (1.0 - covAlpha) * stats.covXY + covAlpha * (resX * resY)))

            stats.meanOffsetX = newMeanX
            stats.meanOffsetY = newMeanY
            stats.sampleCount = min(100_000, stats.sampleCount + 1)

            calibration.perKey[key] = stats
            calibration.totalCommittedTaps = min(10_000_000, calibration.totalCommittedTaps + 1)
            let updatedProfile = makeEffectiveProfile(for: intended, physicalCenter: physCenter)
            effectiveProfiles[intended] = updatedProfile
            let idx = Self.asciiKeyIndex(intended)
            if idx >= 0 {
                profileByIndex[idx] = updatedProfile
            }
            updatedCount += 1
        }

        if updatedCount > 0 {
            dirtyLearnedTapCount += updatedCount
            // Publish the finished alignment to both the worker and the prefix cache.
            modelGeneration &+= 1
        }
        return updatedCount
    }

    @inline(__always)
    public func areKeysAdjacentASCII(_ a: UInt8, _ b: UInt8) -> Bool {
        let ia = Self.asciiByteIndex(a)
        let ib = Self.asciiByteIndex(b)
        guard ia >= 0 && ib >= 0 else { return false }
        if ia == ib { return true }
        return (adjacentMasks[ia] & (UInt32(1) &<< ib)) != 0
    }

    @inline(__always)
    public func areKeysHorizontallyAdjacentASCII(_ a: UInt8, _ b: UInt8) -> Bool {
        let ia = Self.asciiByteIndex(a)
        let ib = Self.asciiByteIndex(b)
        guard ia >= 0 && ib >= 0 else { return false }
        if ia == ib { return true }
        return (horizAdjacentMasks[ia] & (UInt32(1) &<< ib)) != 0
    }

    /// Returns true if `a` and `b` are immediate physical horizontal/vertical/diagonal neighbors on the 26-key layout.
    public func areKeysAdjacent(_ a: Character, _ b: Character) -> Bool {
        if !hasNonASCIILetterAnchor, let va = a.asciiValue, let vb = b.asciiValue {
            let ia = Self.asciiByteIndex(va)
            let ib = Self.asciiByteIndex(vb)
            if ia >= 0 && ib >= 0 {
                return ia == ib || (adjacentMasks[ia] & (UInt32(1) &<< ib)) != 0
            }
        }
        let la = Character(a.lowercased())
        let lb = Character(b.lowercased())
        if la == lb { return true }
        guard let ca = anchorByChar[la], let cb = anchorByChar[lb] else { return false }
        return abs(ca.x - cb.x) <= 0.145 && abs(ca.y - cb.y) <= 0.42
    }

    /// Returns true if `a` and `b` sit side-by-side on the same physical keyboard row (horizontal thumb rollover).
    public func areKeysHorizontallyAdjacent(_ a: Character, _ b: Character) -> Bool {
        if !hasNonASCIILetterAnchor, let va = a.asciiValue, let vb = b.asciiValue {
            let ia = Self.asciiByteIndex(va)
            let ib = Self.asciiByteIndex(vb)
            if ia >= 0 && ib >= 0 {
                return ia == ib || (horizAdjacentMasks[ia] & (UInt32(1) &<< ib)) != 0
            }
        }
        let la = Character(a.lowercased())
        let lb = Character(b.lowercased())
        if la == lb { return true }
        guard let ca = anchorByChar[la], let cb = anchorByChar[lb] else { return false }
        return abs(ca.x - cb.x) <= 0.145 && abs(ca.y - cb.y) <= 0.06
    }

    private struct ScoredIndexDist {
        var idx: Int
        var dist: CGFloat
    }

    private func computeASCIIHypotheses(
        idx: Int,
        sample: TouchSample,
        useAdaptiveCalibration: Bool,
        maxCandidates: Int
    ) -> [KeyHypothesis] {
        let lower = Self.lowerCharByIndex[idx]
        guard maxCandidates > 0 else { return [] }
        let primaryCenter = centerByIndex[idx]
        let rawPoint = sample.normalizedPoint ?? primaryCenter ?? CGPoint(x: 0.5, y: 0.5)
        let point = CGPoint(
            x: min(maxAnchorX, max(minAnchorX, rawPoint.x)),
            y: min(maxAnchorY, max(minAnchorY, rawPoint.y))
        )
        let pointSIMD = SIMD2<Double>(Double(point.x), Double(point.y))
        let applyPersonalProfile = useAdaptiveCalibration
            && !isLandscapeLayout
            && sample.normalizedPoint != nil
            && calibration.totalCommittedTaps > 0

        var mask: UInt32
        if let pc = primaryCenter {
            let dx = abs(point.x - pc.x)
            let dy = abs(point.y - pc.y)
            if dx <= 0.01 && dy <= 0.01 {
                mask = adjacentMasks[idx] | wideMasks165[idx] | (UInt32(1) &<< idx)
            } else if dx <= 0.105 && dy <= 0.04 {
                mask = adjacentMasks[idx] | twoHopMasks[idx] | (UInt32(1) &<< idx)
            } else {
                mask = allAnchorMask
            }
        } else {
            mask = allAnchorMask
        }

        let invTwoSigmaXSq = 1.0 / (2.0 * sigmaX * sigmaX)
        let invTwoSigmaYSq = 1.0 / (2.0 * sigmaY * sigmaY)
        let adjToPrimaryMask = adjacentMasks[idx]

        var stackBuf = (
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0),
            ScoredIndexDist(idx: 0, dist: 0), ScoredIndexDist(idx: 0, dist: 0)
        )

        return withUnsafeMutablePointer(to: &stackBuf) { ptr -> [KeyHypothesis] in
            let items = UnsafeMutableRawPointer(ptr).assumingMemoryBound(to: ScoredIndexDist.self)
            var scoredCount = 0
            var bestDist = CGFloat.greatestFiniteMagnitude

            var rem = mask
            while rem != 0 {
                let cIdx = rem.trailingZeroBitCount
                rem &= rem &- 1
                guard let center = centerByIndex[cIdx] else { continue }
                let physDX = point.x - center.x
                let physDY = point.y - center.y
                let bit = UInt32(1) &<< cIdx
                if cIdx != idx && (adjToPrimaryMask & bit) == 0 && (abs(physDX) > 0.155 || abs(physDY) > 0.42) {
                    continue
                }
                let normDistSq: CGFloat
                if applyPersonalProfile, let prof = profileByIndex[cIdx] {
                    let d = pointSIMD - prof.effectiveCenter
                    normDistSq = CGFloat(max(0.0, simd_dot(d, prof.precisionHalf * d)))
                } else {
                    normDistSq = (physDX * physDX) * invTwoSigmaXSq + (physDY * physDY) * invTwoSigmaYSq
                }
                if normDistSq < bestDist {
                    bestDist = normDistSq
                }
                items[scoredCount] = ScoredIndexDist(idx: cIdx, dist: normDistSq)
                scoredCount += 1
            }

            if scoredCount == 0 {
                return [KeyHypothesis(char: lower, penaltyQ8: 0)]
            }

            let insidePrimaryKeycap: Bool = {
                if applyPersonalProfile, let prof = profileByIndex[idx] {
                    let halfKeyX = Double(keyPitchX) * 0.43
                    let halfKeyY = Double(rowPitchY) * 0.41
                    return abs(pointSIMD.x - prof.effectiveCenter.x) <= halfKeyX
                        && abs(pointSIMD.y - prof.effectiveCenter.y) <= halfKeyY
                }
                guard let pc = primaryCenter else { return true }
                return abs(point.x - pc.x) <= 0.065 && abs(point.y - pc.y) <= 0.20
            }()

            var results: [KeyHypothesis] = []
            results.reserveCapacity(scoredCount + 1)

            let horizMask = horizAdjacentMasks[idx]
            var hasPrimary = false
            for k in 0..<scoredCount {
                let cIdx = items[k].idx
                let ch = Self.lowerCharByIndex[cIdx]
                let dist = items[k].dist
                let rel = max(0, dist - bestDist)
                let penalty: Int
                if cIdx == idx && (rel < 0.08 || insidePrimaryKeycap) {
                    penalty = 0
                } else if rel < 0.50 {
                    let rawPen = Int((rel * 380.0).rounded())
                    penalty = (cIdx == idx) ? rawPen : max(45, rawPen)
                } else {
                    let curvePen: Double = (rel < 0.975)
                        ? (190.0 + (rel - 0.50) * 820.0)
                        : (380.0 + (rel - 0.50) * 420.0)
                    var rawPen = min(1200, Int(curvePen.rounded()))
                    if cIdx != idx && insidePrimaryKeycap {
                        let cBit = UInt32(1) &<< cIdx
                        if (horizMask & cBit) != 0 {
                            rawPen = min(rawPen, 620)
                        } else if (adjToPrimaryMask & cBit) != 0 {
                            rawPen = max(490, min(rawPen, 880))
                        }
                    }
                    penalty = (cIdx == idx) ? rawPen : max(45, rawPen)
                }
                if penalty <= 1020 {
                    if cIdx == idx { hasPrimary = true }
                    results.append(KeyHypothesis(char: ch, penaltyQ8: penalty))
                }
            }

            if !hasPrimary {
                results.append(KeyHypothesis(char: lower, penaltyQ8: insidePrimaryKeycap ? 0 : 120))
            }
            if results.count > 1 {
                results.sort { a, b in
                    if a.penaltyQ8 != b.penaltyQ8 { return a.penaltyQ8 < b.penaltyQ8 }
                    if (a.char == lower) != (b.char == lower) { return a.char == lower }
                    return a.char < b.char
                }
            }
            if results.count > maxCandidates {
                results.removeSubrange(maxCandidates..<results.count)
            }
            return results
        }
    }

    /// Returns up to `maxCandidates` plausible keys for a tap sample, ordered by ascending penalty.
    public func hypotheses(
        for sample: TouchSample,
        enabled: Bool,
        useAdaptiveCalibration: Bool = true,
        maxCandidates: Int = 7
    ) -> [KeyHypothesis] {
        guard maxCandidates > 0 else { return [] }
        let idx = Self.asciiKeyIndex(sample.primaryChar)
        if idx >= 0 && !hasNonASCIILetterAnchor {
            guard enabled else {
                return [KeyHypothesis(char: Self.lowerCharByIndex[idx], penaltyQ8: 0)]
            }
            if sample.normalizedPoint == nil && maxCandidates <= 7,
               let cached = staticCenterHypotheses[idx] {
                if cached.count <= maxCandidates {
                    return cached
                }
                return Array(cached.prefix(maxCandidates))
            }
            return computeASCIIHypotheses(
                idx: idx,
                sample: sample,
                useAdaptiveCalibration: useAdaptiveCalibration,
                maxCandidates: maxCandidates
            )
        }

        let lower = Character(sample.primaryChar.lowercased())
        guard lower >= "a" && lower <= "z" else {
            return [KeyHypothesis(char: lower, penaltyQ8: 0)]
        }
        guard enabled else {
            return [KeyHypothesis(char: lower, penaltyQ8: 0)]
        }

        let primaryCenter = anchorByChar[lower]
        let rawPoint = sample.normalizedPoint ?? primaryCenter ?? CGPoint(x: 0.5, y: 0.5)
        // Clamp outer-bezel landings (e.g. right edge of 'p' at x=1.0 or top of Row 0 at y=0.0) to the
        // physical anchor envelope so 1-key overshoots near screen edges never inflate beyond 1-key pitch.
        let point = CGPoint(
            x: min(maxAnchorX, max(minAnchorX, rawPoint.x)),
            y: min(maxAnchorY, max(minAnchorY, rawPoint.y))
        )
        let pointSIMD = SIMD2<Double>(Double(point.x), Double(point.y))
        let applyPersonalProfile = useAdaptiveCalibration
            && !isLandscapeLayout
            && sample.normalizedPoint != nil
            && calibration.totalCommittedTaps > 0

        var scored: [(Character, CGFloat)] = []
        scored.reserveCapacity(8)

        for anchor in anchors {
            let physDX = point.x - anchor.center.x
            let physDY = point.y - anchor.center.y
            let isAdjacentToPrimary: Bool = {
                guard let pc = primaryCenter else { return false }
                return abs(pc.x - anchor.center.x) <= 0.145 && abs(pc.y - anchor.center.y) <= 0.42
            }()
            // Retain immediate physical neighbors of `lower` plus any key within `(0.155, 0.42)` of `point`,
            // while excluding 2-key jumps.
            if anchor.char != lower && !isAdjacentToPrimary && (abs(physDX) > 0.155 || abs(physDY) > 0.42) {
                continue
            }

            let normDistSq: CGFloat
            if applyPersonalProfile, let prof = effectiveProfiles[anchor.char] {
                let d = pointSIMD - prof.effectiveCenter
                normDistSq = CGFloat(max(0.0, simd_dot(d, prof.precisionHalf * d)))
            } else {
                normDistSq = (physDX * physDX) / (2.0 * sigmaX * sigmaX) + (physDY * physDY) / (2.0 * sigmaY * sigmaY)
            }
            scored.append((anchor.char, normDistSq))
        }

        if scored.isEmpty {
            return [KeyHypothesis(char: lower, penaltyQ8: 0)]
        }

        var bestDist = scored[0].1
        for k in 1..<scored.count {
            if scored[k].1 < bestDist {
                bestDist = scored[k].1
            }
        }
        let insidePrimaryKeycap: Bool = {
            if applyPersonalProfile, let prof = effectiveProfiles[lower] {
                let halfKeyX = Double(keyPitchX) * 0.43
                let halfKeyY = Double(rowPitchY) * 0.41
                return abs(pointSIMD.x - prof.effectiveCenter.x) <= halfKeyX
                    && abs(pointSIMD.y - prof.effectiveCenter.y) <= halfKeyY
            }
            guard let pc = primaryCenter else { return true }
            return abs(point.x - pc.x) <= 0.065 && abs(point.y - pc.y) <= 0.20
        }()

        var results: [KeyHypothesis] = []
        results.reserveCapacity(scored.count + 1)

        // Scale relative squared Mahalanobis distance into Q8 log10 penalty (256 = 10x probability ratio).
        // Borderline/drifted taps (`rel < 0.50`) keep a gentle penalty (~45..190 Q8); dead-center full-pitch
        // horizontal (~561..620 Q8) and vertical/staggered (~752..880 Q8) substitutions rescue blind-typing typos
        // (`nihap`, `mingtisn`, `womdn`, `mkngtian`, `nihal`, `dkanhua`) while preserving clean words (`siji` -> `司机`).
        for (ch, dist) in scored {
            let rel = max(0, dist - bestDist)
            let penalty: Int
            if ch == lower && (rel < 0.08 || insidePrimaryKeycap) {
                penalty = 0
            } else if rel < 0.50 {
                let rawPen = Int((rel * 380.0).rounded())
                penalty = (ch == lower) ? rawPen : max(45, rawPen)
            } else {
                let curvePen: Double = (rel < 0.975)
                    ? (190.0 + (rel - 0.50) * 820.0)
                    : (380.0 + (rel - 0.50) * 420.0)
                var rawPen = min(1200, Int(curvePen.rounded()))
                if ch != lower && insidePrimaryKeycap {
                    if areKeysHorizontallyAdjacent(lower, ch) {
                        rawPen = min(rawPen, 620)
                    } else if areKeysAdjacent(lower, ch) {
                        rawPen = max(490, min(rawPen, 880))
                    }
                }
                penalty = (ch == lower) ? rawPen : max(45, rawPen)
            }
            if penalty <= 1020 {
                results.append(KeyHypothesis(char: ch, penaltyQ8: penalty))
            }
        }

        // Guarantee primary tapped character is always present, and sort deterministically with primaryChar winning ties.
        if !results.contains(where: { $0.char == lower }) {
            results.append(KeyHypothesis(char: lower, penaltyQ8: insidePrimaryKeycap ? 0 : 120))
        }
        results.sort { a, b in
            if a.penaltyQ8 != b.penaltyQ8 { return a.penaltyQ8 < b.penaltyQ8 }
            if (a.char == lower) != (b.char == lower) { return a.char == lower }
            return a.char < b.char
        }
        if results.count > maxCandidates {
            results.removeSubrange(maxCandidates..<results.count)
        }

        return results
    }

    public static func defaultNativeAnchors() -> [KeyAnchor] {
        let row0: [Character] = Array("qwertyuiop")
        let row1: [Character] = Array("asdfghjkl")
        let row2: [Character] = Array("zxcvbnm")

        var list: [KeyAnchor] = []
        list.reserveCapacity(26)

        for (i, ch) in row0.enumerated() {
            list.append(KeyAnchor(char: ch, center: CGPoint(x: 0.05 + CGFloat(i) * 0.10, y: 1.0 / 6.0)))
        }
        for (i, ch) in row1.enumerated() {
            list.append(KeyAnchor(char: ch, center: CGPoint(x: 0.10 + CGFloat(i) * 0.10, y: 3.0 / 6.0)))
        }
        for (i, ch) in row2.enumerated() {
            list.append(KeyAnchor(char: ch, center: CGPoint(x: 0.20 + CGFloat(i) * 0.10, y: 5.0 / 6.0)))
        }
        return list
    }
